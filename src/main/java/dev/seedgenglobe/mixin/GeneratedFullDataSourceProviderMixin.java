package dev.seedgenglobe.mixin;

import java.util.concurrent.atomic.AtomicReference;

import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;

import com.seibel.distanthorizons.core.file.fullDatafile.GeneratedFullDataSourceProvider;
import com.seibel.distanthorizons.core.generation.queues.IFullDataSourceRetrievalQueue;

import dev.seedgenglobe.dh.DhProviderHook;
import dev.seedgenglobe.dh.DhQueueHook;

/**
 * Tells {@link LodQuadTreeMixin}, {@link LodParentRequestMixin} and {@link LodStandInMixin} whether the sections a
 * provider is missing are generated by SeedGenGlobe, and whether anything generates them right now.
 */
@Mixin(value = GeneratedFullDataSourceProvider.class, remap = false)
public abstract class GeneratedFullDataSourceProviderMixin implements DhProviderHook {

	@Shadow @Final private AtomicReference<IFullDataSourceRetrievalQueue> worldGenQueueRef;

	@Override
	public boolean seedgenglobe$generatedBySeedGenGlobe() {
		return this.worldGenQueueRef.get() instanceof DhQueueHook queue && queue.seedgenglobe$generatedBySeedGenGlobe();
	}

	@Override
	public boolean seedgenglobe$canGenerateNow() {
		// Distant Horizons only has a generation (or network) queue while its Distant Generation is on
		return this.worldGenQueueRef.get() != null;
	}
}
