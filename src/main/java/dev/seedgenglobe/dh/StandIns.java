package dev.seedgenglobe.dh;

import java.util.ArrayList;

import com.seibel.distanthorizons.core.dataObjects.render.bufferBuilding.LodBufferContainer;
import com.seibel.distanthorizons.core.file.fullDatafile.V2.FullDataSourceProviderV2;
import com.seibel.distanthorizons.core.level.IDhClientLevel;
import com.seibel.distanthorizons.core.pos.DhSectionPos;
import com.seibel.distanthorizons.core.render.QuadTree.LodRenderSection;
import com.seibel.distanthorizons.core.util.objects.quadTree.QuadNode;
import com.seibel.distanthorizons.core.util.objects.quadTree.QuadTree;
import com.seibel.distanthorizons.core.wrapperInterfaces.world.IClientLevelWrapper;

import it.unimi.dsi.fastutil.longs.LongOpenHashSet;

import dev.seedgenglobe.GlobeConfig;

/**
 * The coarser sections Distant Horizons 3.0.3 draws in place of finer ones ("stand-ins"), in dimensions SeedGenGlobe
 * generates. Used by {@code LodStandInMixin} and {@code LodParentRequestMixin}.
 * <p>
 * Every tick, DH's render tree walks from its root nodes down to the detail level it wants and loads every node on the
 * way, ancestors included. When fewer than four children of a node can be drawn (one of them is still loading, which
 * happens all the time while the player moves), it draws the node itself and switches all four children off
 * ({@code LodQuadTree.onDetailLevelTooLow}). A section with no row in DH's database loads as an empty data source
 * ({@code FullDataSourceProviderV2.get} returns {@code createEmpty}), gets zero vertex buffers and still counts as
 * drawable. DH only asks the generator for the nodes it wants at their own level, never for the stand-ins, and since
 * 1.1.0 SeedGenGlobe's sections do not update their parents ({@link SectionFlags}), so in 1.3.2 nearly every stand-in
 * was such an empty section: moving made holes up to twice the width of the section that was still loading (0.6 % of
 * the detail-6 sections in a tested database had a detail-7 parent).
 * <p>
 * The fixes: an empty stand-in no longer hides the children that did load ({@link #drawsSomething}); DH also asks
 * SeedGenGlobe for the ancestors of the sections it wants ({@link #withParents}), so the stand-ins have terrain; and
 * while DH cannot generate (Distant Generation off, the usual way to play once LODs are built), an empty section it
 * wants gives way to the coarser section around it, so walking towards terrain generated from farther away shows that
 * coarser terrain instead of holes.
 */
public final class StandIns {

	private StandIns() {}

	/** Whether a loaded section has anything to draw: an empty data source uploads zero vertex buffers. */
	public static boolean drawsSomething(LodRenderSection section) {
		LodBufferContainer buffers = section.renderBufferContainer;
		return buffers != null && buffers.vboBufferCount() > 0;
	}

	/** Whether SeedGenGlobe generates the dimension of this Distant Horizons client level (on this side). */
	public static boolean generatedHere(IDhClientLevel level) {
		IClientLevelWrapper wrapper = level.getClientLevelWrapper();
		return wrapper != null && DhBridge.generates(wrapper.getWrappedMcObject());
	}

	/**
	 * Whether this render tree's missing sections are generated by SeedGenGlobe and it should be asked for their
	 * ancestors too: the singleplayer or server generator ({@code GeneratedFullDataSourceProviderMixin}), or this
	 * client's own multiplayer generation ({@code DhClientLevelMixin}). Not with DH's own generator, which would
	 * generate every chunk under a coarse section, nor when the sections come from a Distant Horizons server.
	 */
	public static boolean requestParents(FullDataSourceProviderV2 provider, IDhClientLevel level) {
		if (!GlobeConfig.get().generateParentSections) return false;
		if (provider instanceof DhProviderHook hook && hook.seedgenglobe$generatedBySeedGenGlobe()) return true;
		return level instanceof DhClientLevelHook client && client.seedgenglobe$generatesLocally();
	}

	/**
	 * The nodes Distant Horizons asks generation for this tick, followed by each of their ancestors in the tree (once,
	 * and only those not asked for yet). DH works out per position whether a section is missing or not fully generated
	 * ({@code GeneratedFullDataSourceProvider.getPositionsToRetrieve}: a parent built only from children counts as not
	 * generated), so ancestors already in the database cost nothing.
	 */
	public static ArrayList<QuadNode<LodRenderSection>> withParents(QuadTree<LodRenderSection> tree, ArrayList<QuadNode<LodRenderSection>> nodes) {
		if (nodes.isEmpty()) return nodes;
		ArrayList<QuadNode<LodRenderSection>> result = new ArrayList<>(nodes.size() + nodes.size() / 2);
		result.addAll(nodes);
		LongOpenHashSet seen = new LongOpenHashSet();
		byte root = tree.treeRootDetailLevel;
		for (QuadNode<LodRenderSection> node : nodes) {
			if (node == null) continue;
			long pos = node.sectionPos;
			while (DhSectionPos.getDetailLevel(pos) < root) {
				pos = DhSectionPos.getParentPos(pos);
				if (!seen.add(pos)) break; // this ancestor, and so all of its own, was handled for an earlier node
				QuadNode<LodRenderSection> parent = tree.tryGetNode(pos);
				if (parent == null) break;
				LodRenderSection section = parent.value;
				if (section != null && !section.queuedMissingSectionsForRetrieval) result.add(parent);
			}
		}
		return result;
	}
}
